const I18n = {
    currentLang: 'pl',
    availableLangs: ['pl', 'en', 'es', 'de', 'fr'],
    initialized: false,

    init() {
        if (this.initialized) return;

        // 1. Check LocalStorage
        const saved = localStorage.getItem('bp_lang');

        // 2. Check Browser
        const browser = navigator.language.split('-')[0];

        // 3. Set Current (Saved > Browser > Default 'pl')
        if (saved && this.availableLangs.includes(saved)) {
            this.currentLang = saved;
        } else if (this.availableLangs.includes(browser)) {
            this.currentLang = browser;
        } else {
            this.currentLang = 'pl';
        }

        // Initial translation
        this.updatePage();
        this.initialized = true;
    },

    setLang(lang) {
        if (!translations[lang]) return;
        this.currentLang = lang;
        localStorage.setItem('bp_lang', lang);
        this.updatePage();

        // Re-render components to update Settings toggle and other dynamic parts
        if (window.initComponents && window.currentPage) {
            window.initComponents(window.currentPage);
        }

        // Trigger Dynamic Island refresh if available
        if (window.dynamicIsland && window.dynamicIsland.refresh) {
            window.dynamicIsland.refresh();
        }

        // Dispatch event
        window.dispatchEvent(new CustomEvent('langChanged', { detail: this.currentLang }));

        // Re-init specific views if needed
        // (If the router handles re-render on lang change, this might not be needed, 
        //  but currently main.js listens to langChanged and calls updateDateDisplay, 
        //  we might want to trigger a data re-fetch if region changes? 
        //  Actually region/iso is separate but linked to lang in user mind maybe?)

        // For now, reload the page content wrapper if possible or just let the user navigate.
        // But better UX: re-run the current page init function.
        const currentPath = window.location.pathname;
        if (currentPath === '/' || currentPath.endsWith('index.html')) {
            if (window.initOverviewPage) window.initOverviewPage();
        } else if (currentPath.includes('la-liga')) {
            if (window.initLaLigaPage) window.initLaLigaPage();
        } else if (currentPath.includes('ucl')) {
            if (window.initUCLPage) window.initUCLPage();
        } else if (currentPath.includes('schedule')) {
            if (window.initSchedulePage) window.initSchedulePage();
        }
    },

    t(key) {
        return translations[this.currentLang][key] || key;
    },

    formatDate(dateStr, options = {}) {
        if (!dateStr) return this.t('tbd');
        const date = new Date(dateStr);
        if (isNaN(date.getTime())) return dateStr;

        // Relative date logic
        const now = new Date();
        const today = new Date(now.getFullYear(), now.getMonth(), now.getDate());
        const target = new Date(date.getFullYear(), date.getMonth(), date.getDate());
        const diffDays = Math.round((target - today) / (1000 * 60 * 60 * 24));

        let relative = "";
        if (diffDays === 0) relative = this.t('today');
        else if (diffDays === 1) relative = this.t('tomorrow');
        else if (diffDays === 2) relative = this.t('dayAfterTomorrow');
        else if (diffDays === -1) relative = this.t('yesterday');

        const formattedDate = new Intl.DateTimeFormat(this.currentLang, options).format(date);

        if (relative) {
            return `${relative}, ${formattedDate}`;
        }

        return formattedDate;
    },

    updatePage() {
        document.documentElement.lang = this.currentLang;

        // Translate elements with data-i18n attribute
        document.querySelectorAll('[data-i18n]').forEach(el => {
            const key = el.getAttribute('data-i18n');
            if (key) el.innerText = this.t(key);
        });

        // Translate placeholders
        document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
            const key = el.getAttribute('data-i18n-placeholder');
            if (key) el.placeholder = this.t(key);
        });
    }
};

window.I18n = I18n;
window.t = (key) => I18n.t(key);
